# automata-net: the .emp interpreter (BoolCombinationEmptiness) of VeriFIT's
# Automata.NET fork, branch tacas24, on .mata inputs mintermized by
# scripts/massage_arguments.py.
#
# The project targets net6.0, which no maintained SDK ships, so it is retargeted
# to the SDK's own framework and published framework-dependent: self-contained
# would download runtime packs and its apphost does not run on NixOS.

subject=subjects/automata-net
runs="emp"

build() {
    local src="$outdir/src" publish="$outdir/publish" dotnet python sdk config=Release

    dotnet=$(command -v dotnet) || die "dotnet not found; enter the dev shell"
    dotnet=$(readlink -f "$dotnet")
    [ -f "$worktree/src/BoolCombinationEmptiness/EmpParser.cs" ] ||
        die "revision has no .emp interpreter (src/BoolCombinationEmptiness); use branch tacas24"
    [ "$build_mode" = Debug ] && config=Debug

    export DOTNET_CLI_TELEMETRY_OPTOUT=1 DOTNET_NOLOGO=1 DOTNET_SKIP_FIRST_TIME_EXPERIENCE=1
    sdk=$("$dotnet" --version)

    # A copy keeps obj/ and bin/ out of the shared checkout and is where the
    # projects are retargeted ('-p:TargetFramework' does not reach restore).
    rm -rf "$src" "$publish"
    cp -r "$worktree/src" "$src"
    sed -i "s|<TargetFramework>net6\.0</TargetFramework>|<TargetFramework>net${sdk%%.*}.0</TargetFramework>|" \
        "$src"/*/*.csproj
    # The parser predates '%Alphabet-enum' and reads it as a transition. Its
    # alphabet is the symbols on the transitions anyway, so skip the line.
    sed -i '/else if (tokens\[0\] == "%Initial")/i\                else if (tokens[0].StartsWith("%Alphabet")) { }' \
        "$src/BoolCombinationEmptiness/MataParser.cs"
    grep -q 'StartsWith("%Alphabet")' "$src/BoolCombinationEmptiness/MataParser.cs" ||
        die "MataParser.cs changed; cannot patch it to skip '%Alphabet' lines"
    # Answers are 'result: true|false', as with the other tools (C# prints 'True').
    sed -i 's/Console.WriteLine("\(emptiness\|inclusion\)_result: {0}", \([A-Za-z]*\));/Console.WriteLine("result: {0}", \2 ? "true" : "false");/' \
        "$src/BoolCombinationEmptiness/EmpParser.cs"
    ! grep -q '_result: ' "$src/BoolCombinationEmptiness/EmpParser.cs" ||
        die "EmpParser.cs changed; cannot patch the names it reports"
    # Source Link would read the enclosing benchmark repository, whose git
    # extensions (relativeworktrees) it does not support. SYSLIB0011: since
    # net8.0 BinaryFormatter use is a compile error; the interpreter never
    # serializes. The code emits hundreds of nullable warnings: errors only.
    "$dotnet" publish "$src/BoolCombinationEmptiness/BoolCombinationEmptiness.csproj" \
        --configuration "$config" --output "$publish" \
        -p:SelfContained=false -p:PublishSingleFile=false -p:UseAppHost=false \
        -p:EnableSourceControlManagerQueries=false -p:EnableSourceLink=false \
        -p:NoWarn=SYSLIB0011 -consoleLoggerParameters:ErrorsOnly

    python=$(libmata_python)

    # The interpreter runs any other '(op autN)' as a no-op and exits 0, which
    # would be measured as success: the wrapper rejects such programs.
    # Invariant globalization: the interpreter formats times with the current
    # culture, which may use a decimal comma; it also spares the ICU lookup.
    {
        echo '#!/usr/bin/env bash'
        echo "# Generated by scripts/build_version.sh -- Automata.NET's .emp interpreter."
        printf 'python=%q\nmassage=%q\ndotnet=%q\ninterpreter=%q\n' \
            "$python" "$rootdir/scripts/massage_arguments.py" "$dotnet" "$publish/BoolCombinationEmptiness.dll"
        cat <<'EOF'
set -euo pipefail
[ $# -ge 2 ] || { echo "usage: $0 <program.emp> <automaton.mata>..." >&2; exit 1; }
program=$1
shift
# The interpreter fails on blank and '#' lines: it gets a copy without them.
cleaned=$(mktemp)
trap 'rm -f "$cleaned"' EXIT
while IFS= read -r line || [ -n "$line" ]; do
    read -r -a tokens <<< "${line//[=()]/ }"
    [ ${#tokens[@]} -gt 0 ] && [[ ${tokens[0]} != \#* ]] || continue
    case ${tokens[0]} in
        load_automaton|load_automata|is_empty|incl) op="";;
        aut*) op=${tokens[1]:-};;
        *) op=${tokens[0]};;
    esac
    case $op in
        ''|interall|unionall|compl|union|inter) ;;
        *) echo "error: automata-net does not support '$op'" >&2; exit 1;;
    esac
    printf '%s\n' "$line"
done < "$program" > "$cleaned"
massaged=$("$python" "$massage" "$@")
read -r -a automata <<< "$massaged"
export DOTNET_SYSTEM_GLOBALIZATION_INVARIANT=1 DOTNET_CLI_TELEMETRY_OPTOUT=1 DOTNET_NOLOGO=1
"$dotnet" "$interpreter" "$cleaned" "${automata[@]}"
EOF
    } > "$binary"
    chmod +x "$binary"
}
