# automatalib: LearnLib's AutomataLib emp interpreter (cz.verifit.Automatalib)
# of VeriFIT/mata-comparison-brics, a Java/maven project that also holds brics'.

subject=subjects/mata-comparison-brics
runs="emp"

build() {
    local jar_name=automatalib-emp-interpreter
    local project="$outdir/project" jar="$outdir/$jar_name.jar" java python

    java=$(command -v java) || die "java not found; run in the dev shell"
    java=$(readlink -f "$java")
    command -v mvn >/dev/null || die "mvn not found; run in the dev shell"

    # maven builds into the project's target/; a private copy keeps the tools
    # sharing this checkout from clobbering each other's builds.
    rm -rf "$project"
    mkdir -p "$project"
    git -C "$worktree" archive HEAD | tar -x -C "$project"
    # Answers are 'result' and n-ary intersections 'intersection', as with the other tools.
    local parser="$project/src/main/java/cz/verifit/EmpParser.java"
    sed -i -e 's/"\(emptiness\|inclusion\)_result: "/"result: "/' \
        -e 's/endTimer("interall")/endTimer("intersection")/' "$parser"
    ! grep -q -e '_result: ' -e 'endTimer("interall")' "$parser" ||
        die "EmpParser.java changed; cannot patch the names it reports"
    # The repository below build/ caches the dependencies for later, offline
    # builds; file locks let parallel builds share it.
    JAVA_HOME="${java%/bin/java}" mvn --batch-mode --quiet --file "$project/pom.xml" \
        -Dmaven.repo.local="$rootdir/build/maven-repo" \
        -Daether.syncContext.named.factory=file-lock -Daether.syncContext.named.nameMapper=file-gav \
        package
    cp "$project/target/$jar_name.jar" "$jar"
    rm -rf "$project"

    # The interpreter treats an unknown operation with one operand as a copy
    # of it and exits 0, so the wrapper rejects programs using anything else.
    # 'determinize' is such a copy too, but a sound one: loading an automaton
    # already determinizes it (reported as 'determinize'). concat would throw.
    local ops="load_automaton load_automata is_empty incl interall unionall compl union inter determinize"

    # The interpreter reads explicit automata only: bitvector inputs are
    # mintermized by mata's bindings first (cached under build/minterm/).
    python=$(libmata_python)
    cat >"$binary" <<EOF
#!/usr/bin/env bash
# Generated by scripts/build_version.sh -- automatalib's emp interpreter ($commit).
set -euo pipefail
program=\$1
shift
# The interpreter fails on blank and comment lines: it reads a copy without them.
cleaned=\$(mktemp)
trap 'rm -f "\$cleaned"' EXIT
while IFS= read -r line || [ -n "\$line" ]; do
    read -r first second _ <<< "\${line//[()=]/ }"
    case \$first in ''|'#'*) continue;; esac
    # 'autN = (op ...)' or 'op ...'
    if [[ \$line == *=* ]]; then op=\$second; else op=\$first; fi
    if [[ " $ops " != *" \$op "* ]]; then
        echo "error: automatalib does not support '\$op'" >&2
        exit 1
    fi
    printf '%s\n' "\$line"
done < "\$program" > "\$cleaned"
massaged=\$("$python" "$rootdir/scripts/massage_arguments.py" "\$@")
read -ra automata <<< "\$massaged"
"$java" -jar "$jar" "\$cleaned" "\${automata[@]}"
EOF
    chmod +x "$binary"
}
