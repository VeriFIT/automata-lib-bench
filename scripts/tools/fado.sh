# fado: pyinterpret's FadoEngine on FAdo of the given PyPI version.
#
# Inputs are parsed with mata's bindings at the pinned parsing revision; the
# venv reaches them through a .pth file instead of building libmata again.

subject=pypi:fado
runs="emp"

build() {
    local venv="$outdir/venv" mata_python site

    command -v uv >/dev/null || die "uv not found; enter the dev shell or run 'just bootstrap'"
    mata_python=$(libmata_python)

    rm -rf "$venv"
    # uv's own downloaded CPython does not run on NixOS; use the shell's.
    uv venv "$venv" --python "$(command -v python3)" >/dev/null
    [ "$("$venv/bin/python" -c 'import sys; print(sys.version_info[:2])')" = \
        "$("$mata_python" -c 'import sys; print(sys.version_info[:2])')" ] ||
        die "python3 differs from the one mata's bindings were built with ($mata_python)"
    # --no-deps: pyinterpret requires libmata, which comes from the .pth below.
    VIRTUAL_ENV="$venv" uv pip install --no-deps "$harness/src/python"
    VIRTUAL_ENV="$venv" uv pip install "fado==$rev"
    site=$("$venv/bin/python" -c 'import sysconfig; print(sysconfig.get_path("platlib"))')
    "$mata_python" -c 'import sysconfig; print(sysconfig.get_path("platlib"))' >"$site/libmata.pth"

    cat >"$binary" <<EOF
#!/usr/bin/env bash
# Generated by scripts/build_version.sh -- pyinterpret on FAdo $rev.
# The dev shell's PYTHONPATH would shadow the venv's pinned dependencies.
unset PYTHONPATH
exec "$venv/bin/pyinterpret" FadoEngine "\$@"
EOF
    chmod +x "$binary"
}
